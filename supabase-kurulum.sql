-- ---------- 1) YÖNETİCİLER ----------
create table if not exists public.yoneticiler (
  user_id uuid primary key references auth.users(id) on delete cascade,
  eposta  text,
  created_at timestamptz not null default now()
);
alter table public.yoneticiler enable row level security;

-- Giriş yapan kişi yönetici mi? (güvenlik kurallarında kullanılır)
create or replace function public.yonetici_mi()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.yoneticiler where user_id = auth.uid());
$$;

drop policy if exists "yonetici kendini gorur" on public.yoneticiler;
create policy "yonetici kendini gorur" on public.yoneticiler
  for select to authenticated using (user_id = auth.uid());

-- Authentication → Users'a eklenmiş tüm kullanıcıları yönetici yap
insert into public.yoneticiler (user_id, eposta)
select id, email from auth.users
on conflict (user_id) do nothing;


-- ---------- 2) İLANLAR ----------
create table if not exists public.ilanlar (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  baslik        text not null check (char_length(baslik) between 3 and 200),
  tip           text not null default 'Satılık' check (tip in ('Satılık', 'Kiralık')),
  kategori      text not null default 'Daire',
  fiyat         numeric(14,2),
  il            text not null default 'Osmaniye',
  ilce          text,
  mahalle       text,
  brut_m2       integer,
  net_m2        integer,
  oda_sayisi    text,
  banyo_sayisi  integer,
  bina_yasi     integer,
  bulundugu_kat text,
  kat_sayisi    integer,
  isitma        text,
  esyali        boolean not null default false,
  balkon        boolean not null default false,
  asansor       boolean not null default false,
  otopark       boolean not null default false,
  site_icinde   boolean not null default false,
  krediye_uygun boolean not null default false,
  takas         boolean not null default false,
  tapu_durumu   text,
  imar_durumu   text,
  aidat         numeric(12,2),
  aciklama      text,
  ozellikler    text[] not null default '{}',
  resimler      text[] not null default '{}',
  enlem         double precision,
  boylam        double precision,
  one_cikan     boolean not null default false,
  yayinda       boolean not null default true,
  goruntulenme  integer not null default 0
);
create index if not exists ilanlar_yayinda_idx on public.ilanlar (yayinda, created_at desc);

-- Güncellenme tarihini otomatik tut
create or replace function public.guncelleme_tarihi()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
drop trigger if exists ilanlar_guncelleme on public.ilanlar;
create trigger ilanlar_guncelleme before update on public.ilanlar
  for each row execute function public.guncelleme_tarihi();

alter table public.ilanlar enable row level security;

-- ---------- İLAN DURUMU (Aktif / Satıldı / Kiralandı / Pasif) ----------
-- Satıldı, Kiralandı veya Pasif yapılan ilan 30 gün boyunca kendi sayfasında
-- bilgi notuyla görünür (listelerde görünmez), sonra ziyaretçilerden gizlenir.
alter table public.ilanlar add column if not exists durum text not null default 'Aktif';
alter table public.ilanlar add column if not exists durum_tarihi timestamptz;
alter table public.ilanlar drop constraint if exists ilanlar_durum_kontrol;
alter table public.ilanlar add constraint ilanlar_durum_kontrol
  check (durum in ('Aktif', 'Satıldı', 'Kiralandı', 'Pasif'));

create or replace function public.ilan_durum_tarihi()
returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' or new.durum is distinct from old.durum then
    new.durum_tarihi = case when new.durum = 'Aktif' then null else now() end;
  end if;
  return new;
end; $$;
drop trigger if exists ilanlar_durum_tarihi on public.ilanlar;
create trigger ilanlar_durum_tarihi before insert or update on public.ilanlar
  for each row execute function public.ilan_durum_tarihi();

drop policy if exists "ilan okuma" on public.ilanlar;
create policy "ilan okuma" on public.ilanlar
  for select using (
    (yayinda = true and (durum = 'Aktif' or durum_tarihi > now() - interval '30 days'))
    or public.yonetici_mi()
  );

drop policy if exists "ilan ekleme" on public.ilanlar;
create policy "ilan ekleme" on public.ilanlar
  for insert to authenticated with check (public.yonetici_mi());

drop policy if exists "ilan guncelleme" on public.ilanlar;
create policy "ilan guncelleme" on public.ilanlar
  for update to authenticated using (public.yonetici_mi()) with check (public.yonetici_mi());

drop policy if exists "ilan silme" on public.ilanlar;
create policy "ilan silme" on public.ilanlar
  for delete to authenticated using (public.yonetici_mi());

-- Ziyaretçi ilanı açınca görüntülenme sayısını 1 artırır (başka hiçbir şeyi değiştiremez)
create or replace function public.ilan_goruntulendi(ilan_no bigint)
returns void
language sql security definer
set search_path = public
as $$
  update public.ilanlar set goruntulenme = goruntulenme + 1
  where id = ilan_no and yayinda = true;
$$;


-- ---------- 3) MESAJLAR (iletişim formları) ----------
create table if not exists public.mesajlar (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  tur        text not null default 'İletişim' check (char_length(tur) <= 50),
  ad_soyad   text not null check (char_length(ad_soyad) between 2 and 100),
  telefon    text check (char_length(telefon) <= 30),
  eposta     text check (char_length(eposta) <= 120),
  konu       text check (char_length(konu) <= 120),
  mesaj      text check (char_length(mesaj) <= 3000),
  ilan_id    bigint references public.ilanlar(id) on delete set null,
  okundu     boolean not null default false
);
alter table public.mesajlar enable row level security;

-- Ziyaretçiler sadece mesaj GÖNDEREBİLİR, kimse başkasının mesajını okuyamaz
drop policy if exists "mesaj gonderme" on public.mesajlar;
create policy "mesaj gonderme" on public.mesajlar
  for insert to anon, authenticated with check (okundu = false);

drop policy if exists "mesaj okuma" on public.mesajlar;
create policy "mesaj okuma" on public.mesajlar
  for select to authenticated using (public.yonetici_mi());

drop policy if exists "mesaj guncelleme" on public.mesajlar;
create policy "mesaj guncelleme" on public.mesajlar
  for update to authenticated using (public.yonetici_mi()) with check (public.yonetici_mi());

drop policy if exists "mesaj silme" on public.mesajlar;
create policy "mesaj silme" on public.mesajlar
  for delete to authenticated using (public.yonetici_mi());


